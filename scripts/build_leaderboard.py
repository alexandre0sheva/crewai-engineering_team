"""Build the public leaderboard from the committed benchmark batches.

    uv run python scripts/build_leaderboard.py            # write the page, JSON and README rows
    uv run python scripts/build_leaderboard.py --check    # exit 1 when a generated file is stale

Every batch under ``benchmarks/results/`` (a directory with a ``batch.json``) gives one row per
contender (a strategy of the team, or an external agent). The numbers come from the batch's
``results.json`` (the T8 schema, ``bench/export.py``); batches written before it existed (0.2.0)
have only their per-run ``result.json`` files, and the same document is built from those, so old
and new results appear side by side. Offline (``fake``) batches are left out: they measure the
harness, not a model. Writes ``docs/leaderboard.md`` (a sortable table), the same rows as
``docs/assets/leaderboard.json`` and the three-row summary between the markers in ``README.md``.

Nothing here is hand-written: a row is as good as the batch behind it, and each links to it.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from collections.abc import Iterable, Sequence
from dataclasses import asdict, dataclass
from html import escape
from pathlib import Path
from typing import Any

from engineering_team.bench.export import RESULTS_FILE, results_document
from engineering_team.bench.report import money, seconds
from engineering_team.bench.results import COUNTED, collect_results, read_batch

ROOT = Path(__file__).resolve().parent.parent
REPOSITORY = "https://github.com/alexandre0sheva/crewai-engineering_team"
MIN_RUNS = 10  # fewer counted runs than this and a row is shown greyed with "n < 10"
README_ROWS = 3
README_START = "<!-- leaderboard:start (generated by scripts/build_leaderboard.py) -->"
README_END = "<!-- leaderboard:end -->"
RECORD_DIRECTORIES = {"ws", "repo", "crewai-storage"}  # a run's own files, never a batch
DATE = re.compile(r"^\d{4}-\d{2}-\d{2}$")


@dataclass(frozen=True)
class Row:
    """One contender in one batch."""

    contender: str
    kind: str  # strategy | agent
    models: str
    provider: str
    billing: str
    tasks: int
    runs: int  # counted runs: passed, failed or timed out
    passed: int
    rate: float
    low: float
    high: float
    cost_per_success: float | None
    equivalent_per_run: float | None
    median_seconds: float | None
    date: str
    version: str  # engineering_team (and the agent's own version for an agent)
    crewai: str
    batch: str  # path of the batch below benchmarks/results/
    link: str

    @property
    def small(self) -> bool:
        return self.runs < MIN_RUNS


def batch_directories(results: Path) -> list[Path]:
    """Every batch directory under ``results``, in path order."""

    return sorted(
        path.parent
        for path in results.rglob("batch.json")
        if not RECORD_DIRECTORIES & set(path.relative_to(results).parts)
    )


def document_for(batch_dir: Path) -> dict[str, Any] | None:
    """The batch's ``results.json``, or the same document built from its run records."""

    try:
        stored = json.loads((batch_dir / RESULTS_FILE).read_text(encoding="utf-8"))
    except (OSError, ValueError):
        stored = None
    if isinstance(stored, dict) and isinstance(stored.get("contenders"), list):
        return stored
    records = collect_results(batch_dir)
    return results_document(read_batch(batch_dir), records) if records else None


def rows_for(batch_dir: Path, results: Path, link_base: str = REPOSITORY) -> list[Row]:
    document = document_for(batch_dir)
    if document is None or document.get("fake"):
        return []
    relative = batch_dir.relative_to(results).as_posix()
    date = next((part for part in relative.split("/") if DATE.match(part)), "")
    versions = document.get("versions") or {}
    runs = document.get("runs") or []
    rows = []
    for entry in document["contenders"]:
        counted = int(entry.get("counted") or 0)
        if not counted:
            continue
        name = entry["name"]
        own = [r for r in runs if (r.get("agent") or r.get("strategy")) == name]
        providers = sorted({r["provider"] for r in own if r.get("provider")})
        version = str(versions.get("engineering_team") or "?")
        if entry.get("version"):
            version = f"{name} {entry['version']} · harness {version}"
        rows.append(
            Row(
                contender=name,
                kind=str(entry.get("kind") or "strategy"),
                models=", ".join(entry.get("models") or []),
                provider="/".join(providers),
                billing=str(entry.get("billing") or ""),
                tasks=len({r["task"] for r in own if r.get("outcome") in COUNTED}),
                runs=counted,
                passed=int(entry["passed"]),
                rate=float(entry["pass_rate"]),
                low=float(entry["wilson_low"]),
                high=float(entry["wilson_high"]),
                cost_per_success=entry.get("cost_per_success_usd"),
                equivalent_per_run=(
                    entry["equivalent_cost_total_usd"] / counted
                    if entry.get("equivalent_cost_total_usd") is not None
                    else None
                ),
                median_seconds=entry.get("median_duration_seconds"),
                date=date,
                version=version,
                crewai=str(versions.get("crewai") or ""),
                batch=relative,
                link=f"{link_base}/tree/main/benchmarks/results/{relative}",
            )
        )
    return rows


def ordered(rows: Iterable[Row]) -> list[Row]:
    """Enough runs first, then the interval's lower bound (a 3/3 does not beat 9/10), then the
    price of a success; ties go to the newer batch, then by name, so the order never depends on
    the disk (each sort is stable)."""

    rows = sorted(rows, key=lambda r: (r.batch, r.contender))
    rows = sorted(rows, key=lambda r: r.date, reverse=True)
    return sorted(
        rows,
        key=lambda r: (
            r.small,
            -r.low,
            -r.rate,
            r.cost_per_success is None,
            r.cost_per_success or 0.0,
        ),
    )


def collect(results: Path, link_base: str = REPOSITORY) -> list[Row]:
    rows = [
        row for batch in batch_directories(results) for row in rows_for(batch, results, link_base)
    ]
    return ordered(rows)


def cost_text(row: Row) -> str:
    if row.billing == "subscription":
        if row.equivalent_per_run is None:
            return "plan"
        return f"plan (≈{money(row.equivalent_per_run)}/run)"
    return money(row.cost_per_success) if row.passed else "–"


def rate_text(row: Row) -> str:
    return f"{row.rate:.0%} ({row.low:.0%}–{row.high:.0%})"


def what_text(row: Row) -> str:
    return row.models or row.provider or "–"


HEADERS = [
    ("Contender", "text"), ("Model", "text"), ("Pass rate (95 % interval)", "number"),
    ("Passed", "number"), ("Cost / success", "number"), ("Median time", "number"),
    ("Tasks", "number"), ("Date", "text"), ("Version", "text"), ("Batch", "text"),
]  # fmt: skip


def html_row(row: Row) -> str:
    small = f'<span class="lb-note">n &lt; {MIN_RUNS}</span>' if row.small else ""
    cost = 1e9 if row.cost_per_success is None else row.cost_per_success  # unknown sorts last
    cells = [
        (
            escape(row.contender) + (" <small>(agent)</small>" if row.kind == "agent" else ""),
            row.contender,
        ),
        (escape(what_text(row)), what_text(row)),
        (escape(rate_text(row)), f"{row.rate:.6f}"),
        (f"{row.passed}/{row.runs} {small}".strip(), f"{row.runs:06d}"),
        (escape(cost_text(row)), f"{cost:.6f}"),
        (escape(seconds(row.median_seconds)), f"{row.median_seconds or 0:.1f}"),
        (str(row.tasks), f"{row.tasks:04d}"),
        (row.date, row.date),
        (escape(row.version), row.version),
        (f'<a href="{escape(row.link)}">{escape(row.batch)}</a>', row.batch),
    ]
    tds = "".join(f'<td data-sort="{escape(key)}">{text}</td>' for text, key in cells)
    return f'<tr class="{"lb-small" if row.small else "lb-row"}">{tds}</tr>'


def page(rows: Sequence[Row]) -> str:
    head = "".join(
        f'<th data-type="{kind}" scope="col">{escape(name)}</th>' for name, kind in HEADERS
    )
    body = "\n".join(html_row(row) for row in rows)
    return f"""<!-- Generated by scripts/build_leaderboard.py: do not edit. -->
# Leaderboard

What the team (and, where measured, other coding agents) did on the benchmark tasks: every number
comes from a committed batch under
[`benchmarks/results/`]({REPOSITORY}/tree/main/benchmarks/results) and links back to it. Click a
column to sort. The tasks are judged by hidden behavioural checks the agents never see, so a pass
means the behaviour held, not that the agent said so.

**How to read it.** The interval is the 95 % Wilson interval of the pass rate: with {MIN_RUNS} runs
it is wide, and two rows whose intervals overlap are not shown to differ. *Cost / success* is all
the money a batch spent (failed runs included) divided by its successes. Rows with fewer than
{MIN_RUNS} counted runs are greyed and marked *n &lt; {MIN_RUNS}*: they are probes and screens, kept
for the record, not evidence. Runs billed by a subscription show *plan*, never $0. Rows before
0.3.0 carry the version that produced them; method, limits and caveats are in
[Benchmarks](BENCHMARKS.md#limits-of-this-evaluation).

<div class="md-typeset__scrollwrap"><div class="md-typeset__table">
<table class="leaderboard sortable">
<thead><tr>{head}</tr></thead>
<tbody>
{body}
</tbody>
</table>
</div></div>

{len(rows)} rows from {len({row.batch for row in rows})} batches. The same rows as data:
[`leaderboard.json`](assets/leaderboard.json). Rebuild with
`uv run python scripts/build_leaderboard.py` ([CONTRIBUTING](../CONTRIBUTING.md#the-website)).
"""


def readme_block(rows: Sequence[Row], site: str) -> str:
    """The three best rows, enough-runs rows first (``ordered`` already puts them there)."""

    top = list(rows)[:README_ROWS]
    lines = [
        README_START,
        "| Contender | Model | Pass rate (95 % interval) | Cost / success | Runs | Date |",
        "|-----------|-------|---------------------------|----------------|------|------|",
    ]
    for row in top:
        runs = f"{row.runs}" + (" (n < 10)" if row.small else "")
        lines.append(
            f"| `{row.contender}` | {what_text(row)} | {rate_text(row)} | {cost_text(row)} "
            f"| {runs} | [{row.date}]({row.link}) |"
        )
    lines += [
        "",
        f"Top rows of the [leaderboard]({site}leaderboard/), which lists every batch.",
        README_END,
    ]
    return "\n".join(lines)


def replace_block(text: str, block: str) -> str:
    start, end = text.find(README_START), text.find(README_END)
    if start < 0 or end < start:
        raise SystemExit(f"README.md needs the markers {README_START!r} and {README_END!r}.")
    return text[:start] + block + text[end + len(README_END) :]


def outputs(rows: Sequence[Row], readme: Path | None, site: str) -> dict[Path, str]:
    docs = ROOT / "docs"
    produced = {
        docs / "leaderboard.md": page(rows),
        docs / "assets" / "leaderboard.json": json.dumps(
            {"min_runs": MIN_RUNS, "rows": [asdict(row) for row in rows]}, indent=2) + "\n",
    }  # fmt: skip
    if readme is not None:
        produced[readme] = replace_block(
            readme.read_text(encoding="utf-8"), readme_block(rows, site)
        )
    return produced


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="fail when a generated file is stale")
    parser.add_argument("--results", type=Path, default=ROOT / "benchmarks" / "results")
    parser.add_argument("--readme", type=Path, default=ROOT / "README.md")
    parser.add_argument("--no-readme", action="store_true", help="leave README.md alone")
    parser.add_argument(
        "--site", default="https://alexandre0sheva.github.io/crewai-engineering_team/"
    )
    args = parser.parse_args(argv)
    rows = collect(args.results)
    produced = outputs(rows, None if args.no_readme else args.readme, args.site)
    stale = [p for p, text in produced.items() if not p.exists() or p.read_text("utf-8") != text]
    if args.check:
        for path in stale:
            print(f"{path.relative_to(ROOT)} is stale: run scripts/build_leaderboard.py")
        return 1 if stale else 0
    for path in stale:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(produced[path], encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)}")
    print(f"{len(rows)} leaderboard rows.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
